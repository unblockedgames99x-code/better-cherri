import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {patchGamesMusic} from './patch-games-music.mjs';
import {patchBranding,brandingCss} from './patch-branding.mjs';
import {patchNavigation} from './patch-nav.mjs';
import {patchStandardCherri} from './patch-standard-cherri.mjs';
import {patchRemoteProxy} from './patch-remote-proxy.mjs';
import {patchTransportFactory} from './patch-remote-transport.mjs';
import {patchRemoteMedia} from './patch-remote-media.mjs';

const repo=path.resolve('work/cherri');
const staged=path.resolve('work/remote-cherri');
if(!fs.existsSync(path.join(staged,'b')))fs.cpSync(path.join(repo,'b'),path.join(staged,'b'),{recursive:true});
const original=execFileSync('git',['show','HEAD:b/assets/bundle-i7rlf846.js'],{cwd:repo,maxBuffer:20*1024*1024}).toString('utf8');
let source=patchGamesMusic(original).source;
source=patchBranding(source);
source=patchNavigation(source).source;
source=patchStandardCherri(source);
source=patchRemoteProxy(source).source;
source=patchTransportFactory(source);
source=patchRemoteMedia(source).source;
new vm.Script(source,{filename:'better-cherri-online.js'});
fs.writeFileSync(path.join(staged,'b/assets/bundle-i7rlf846.js'),source);
const css=execFileSync('git',['show','HEAD:b/assets/index-B8wtnshq-4811c2da.css'],{cwd:repo,maxBuffer:2*1024*1024}).toString('utf8');
fs.writeFileSync(path.join(staged,'b/assets/index-B8wtnshq-4811c2da.css'),css+brandingCss);
fs.copyFileSync('work/better-remote-transport.js',path.join(staged,'b/better-remote-transport.js'));
fs.copyFileSync(path.join(repo,'LICENSE'),path.join(staged,'LICENSE'));
console.log(JSON.stringify({staged,bytes:Buffer.byteLength(source),upstream:'https://cherrion.top',chat:'original Cherri'}));
