import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {patchNavigation} from './patch-nav.mjs';

const target=path.resolve(process.argv[2]||'work/cherri/b/assets/bundle-i7rlf846.js');
const input=fs.readFileSync(target,'utf8');
const source=input.includes('function betterCherriHostWindow(){')?input:patchNavigation(input).source;
new vm.Script(source);
const helpers=source.slice(source.indexOf('function betterCherriHostWindow(){'),source.indexOf('function cCA(){'));
const detect=source.slice(source.indexOf('function xn(){'),source.indexOf('function mh(){'));
const crossOrigin=new Proxy({}, {get(){throw Error('Cross-origin access denied')}});
const window={parent:crossOrigin};
const context={window};vm.createContext(context);vm.runInContext(helpers+detect,context);
assert.equal(context.betterCherriHostWindow(),null);
assert.equal(context.xn(),false);
let fallback=0,navigation=[];
context.Vt('cherri://g',()=>fallback++);assert.equal(fallback,1);
window.__cherriHost=true;window.__cherriNavigate=url=>navigation.push(url);
assert.equal(context.betterCherriHostWindow(),window);
assert.equal(context.xn(),true);
context.Vt('cherri://g',()=>fallback++);assert.deepEqual(navigation,['cherri://g']);assert.equal(fallback,1);
delete window.__cherriHost;delete window.__cherriNavigate;
const parent={__cherriHost:true,__cherriNavigate:url=>navigation.push(url)};window.parent=parent;
assert.equal(context.betterCherriHostWindow(),parent);
context.Vt('cherri://music',()=>fallback++);assert.deepEqual(navigation,['cherri://g','cherri://music']);
window.parent=window;assert.equal(context.xn(),false);context.Vt('/g',()=>fallback++);assert.equal(fallback,2);
window.__cherriHost=true;let posted;window.postMessage=(data,origin)=>{posted={data,origin}};
vm.runInContext('(betterCherriHostWindow()||window.parent).postMessage({type:"cherri:music:request-state"},"*")',context);
assert.equal(posted.data.type,'cherri:music:request-state');assert.equal(posted.origin,'*');
console.log(JSON.stringify({passed:true,cases:['top-level host','framed own host','cross-origin fallback','same-origin parent host','self-directed music messages','full bundle parse']}));
